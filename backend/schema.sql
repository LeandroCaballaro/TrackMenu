-- Habilitar Políticas RLS básicas para acceso público/autenticado
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tables ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Lectura pública de productos" ON public.products FOR SELECT USING (true);
CREATE POLICY "Lectura pública de mesas" ON public.tables FOR SELECT USING (true);
CREATE POLICY "Actualización pública de mesas" ON public.tables FOR UPDATE USING (true);
CREATE POLICY "Lectura pública de pedidos" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Inserción pública de pedidos" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Actualización pública de pedidos" ON public.orders FOR UPDATE USING (true);
