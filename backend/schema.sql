-- 1. Tabla de Productos
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  price NUMERIC(10, 2) NOT NULL,
  category TEXT DEFAULT 'Hamburguesas',
  image TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabla de Mesas
CREATE TABLE IF NOT EXISTS public.tables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number INT UNIQUE NOT NULL,
  status TEXT DEFAULT 'libre' CHECK (status IN ('libre', 'ocupada')),
  current_order JSONB DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Tabla de Pedidos / Comandas
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_number INT NOT NULL,
  status TEXT DEFAULT 'en_preparacion' CHECK (status IN ('en_preparacion', 'listo', 'entregado', 'cancelado')),
  time TEXT,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  total NUMERIC(10, 2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

